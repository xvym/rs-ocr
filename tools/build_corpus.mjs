import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {reconstruct} from './corpus_source.mjs';
import {sha256, read, hex, parseAligned, parseRsc, parseDictionary, csv, tokensIn, termKey, sourceBytes, toSourceEnglish, applyReview} from './corpus_common.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(read(path.join(root,'corpus/sources.json')));
const out = path.resolve(root, process.argv[2] || 'outputs/corpus-mapping');
fs.mkdirSync(out,{recursive:true});
const writeJson = (file,value) => fs.writeFileSync(path.join(out,file),JSON.stringify(value,null,2)+'\n');
const writeCsv = (file,rows,columns) => fs.writeFileSync(path.join(out,file),csv(rows,columns));
for (const s of manifest.sources) {
  if (sha256(fs.readFileSync(path.join(root,s.local))) !== s.sha256) throw Error(`Hash mismatch: ${s.local}`);
}
const input = basename => {
  const s = manifest.sources.find(s => path.basename(s.local) === basename);
  if (!s) throw Error(`Unpinned source: ${basename}`);
  return {source:s, text:read(path.join(root,s.local))};
};
const records = parseAligned(input('qid_msg.txt').text,input('ja-Hrkt_msg.txt').text,input('en_msg.txt').text);
if (records.length !== 13479) throw Error(`Unexpected RS record count ${records.length}`);
const archive = manifest.sources.find(s => s.path === 'source archive');
// Re-extract the *verified archive* to an isolated ignored cache. A modified old source tree is never trusted.
const extractedRoot = path.join(root,'.tools/corpus-source',`pokeruby-${archive.commit}`);
if (!fs.existsSync(path.join(extractedRoot,'charmap.txt'))) {
  throw Error('Extract the pinned source archive first: see corpus/README.md');
}
// Verify all source bytes against a tree hash manifest generated by prepare_corpus.mjs.
const treeManifest = JSON.parse(read(path.join(root,'.tools/corpus-source/tree.json')));
if (treeManifest.archiveSha256 !== archive.sha256) throw Error('Wrong source archive');
for (const f of treeManifest.files) {
  if (sha256(fs.readFileSync(path.join(extractedRoot,f.path))) !== f.sha256) throw Error(`Source changed: ${f.path}`);
}
const candidates = [], sourceLinks = [], gaps = [], rscRows = [], engineSummary = {};
const corrections = [
  {game:'ruby',recorded:0x3CAE94,corrected:0x3CAEB0,reason:'Rain Dance: pointer-table address replaced with actual text address'},
  {game:'ruby',recorded:0x3EC2761,corrected:0x3EC261,reason:'Wynaut Doll: address outside original ROM replaced with structure member'},
];
const dictionaries = [
  ['species_names','宝可梦名称_英-中_现行官译版.txt','species'],
  ['move_names','技能名称_英-中_现行官译版.txt','move'],
  ['ability_names','特性名称_英-中_官译版.txt','ability'],
  ['items','道具名称_英-中_现行官译版.txt','item'],
].map(([group,file,type]) => {const x=input(file);return {group,type,source:x.source,entries:parseDictionary(x.text)};});
const dictionaryByGroup = new Map(dictionaries.map(d => [d.group,d]));
for (const game of ['ruby','sapphire']) {
  const engine = reconstruct(extractedRoot,path.join(root,input(`poke${game}_rev2.sym`).source.local),game);
  if (engine.errors.length) throw Error(`Source reconstruction errors: ${JSON.stringify(engine.errors)}`);
  const rawRsc = input((game==='ruby'?'红宝石':'蓝宝石')+'1.2汉化总文本(JP).txt');
  const entries = parseRsc(rawRsc.text);
  if (entries.length !== 9805) throw Error(`Unexpected RSC count: ${game}`);
  const chineseAt = new Map();
  for (const e of entries) {
    const correction = corrections.find(c => c.game===game && c.recorded===e.address);
    const address = correction?.corrected ?? e.address;
    const bytes = sourceBytes(engine.memory,address), owner=engine.owners.get(address);
    if (!bytes || !owner) throw Error(`Unreconstructed corrected RSC address: ${game} ${hex(address)}`);
    const base = owner.name.replace(/\[.*$/, '');
    const row = {game,index:e.index,sourceId:rawRsc.source.id,recordedAddress:hex(e.address),address:hex(address),
      declaredBytes:e.declaredBytes,actualBytes:bytes.length,sourceSymbol:owner.name,
      symbolAddress:hex(engine.symbols.get(base).address),offsetWithinSymbol:address-engine.symbols.get(base).address,
      offsetWithinField:address-owner.start,sourceFile:owner.file,chinese:e.chinese,
      correction:correction?.reason??'',englishBytesSha256:sha256(bytes)};
    rscRows.push(row);
    const list = chineseAt.get(address) || []; list.push(row); chineseAt.set(address,list);
  }
  // Index source starts and all RSC interior offsets. Never slice by the translated byte count.
  const starts = new Set([...engine.owners.values()].map(o => o.start));
  for (const address of chineseAt.keys()) starts.add(address);
  const englishIndex = new Map();
  for (const address of starts) {
    const bytes = sourceBytes(engine.memory,address);
    if (!bytes || !bytes.length) continue;
    const key = bytes.toString('hex'), list=englishIndex.get(key)||[];
    list.push(address); englishIndex.set(key,list);
  }
  const rev0 = new Map();
  for (const m of input(`poke${game}.sym`).text.matchAll(/^([\da-f]{8})\s+\S\s+[\da-f]{8}\s+(\S+)$/gmi)) {
    const address=parseInt(m[1],16)-0x08000000;
    const list=rev0.get(address)||[]; list.push(m[2]); rev0.set(address,list);
  }
  let encodingErrors=0;
  for (const r of records) {
    const candidateStart=candidates.length;
    if (r.game!=='both' && r.game!==game) continue;
    if (!r.japanese || r.japanese==='[NULL]') {gaps.push({qid:r.qid,game,reason:'japanese_absent'});continue;}
    if (!r.english || r.english==='[NULL]') {gaps.push({qid:r.qid,game,reason:'english_absent'});continue;}
    let addresses=[],error='';
    try {addresses=englishIndex.get(Buffer.from(engine.encode(toSourceEnglish(r.english))).toString('hex'))||[];}
    catch(e) {error=e.message;encodingErrors++;}
    const idParts=r.qid.split('.'), group=idParts[2], legacyName=idParts[3];
    const oldAddress=legacyName.match(/(?:_|String_)([\da-fA-F]{6,8})$/);
    const aliases=oldAddress ? rev0.get(parseInt(oldAddress[1],16)&0x1FFFFFF)||[] : [];
    // Prefer explicit symbol/member evidence only when its English bytes also match.
    const structural=addresses.filter(a => {
      const owner=engine.owners.get(a),base=owner.name.replace(/\[.*$/, '');
      if (idParts[4] && /^\d+$/.test(idParts[4])) {
        const layout={gSpeciesNames:[11,0],gMoveNames:[13,0],gTypeNames:[7,0],gAbilityNames:[13,0],gItems:[44,0],gTrainers:[40,4],gTrainerClassNames:[13,0]}[legacyName];
        if(layout && engine.symbols.has(legacyName)) return a===engine.symbols.get(legacyName).address+Number(idParts[4])*layout[0]+layout[1];
        return owner.name===`${legacyName}[${idParts[4]}]+0`;
      }
      return base===legacyName || aliases.includes(base);
    });
    if (structural.length) addresses=structural;
    for (const address of addresses) {
      const owner=engine.owners.get(address),base=owner.name.replace(/\[.*$/, '');
      const link={qid:r.qid,game,address:hex(address),sourceSymbol:owner.name,sourceFile:owner.file,
        symbolAddress:hex(engine.symbols.get(base).address),offsetWithinSymbol:address-engine.symbols.get(base).address,
        evidence:structural.length?'symbol_or_rev0_alias_and_exact_english_bytes':'exact_english_bytes_candidate',
        legacySymbol:legacyName};
      sourceLinks.push(link);
      for (const c of chineseAt.get(address)||[]) candidates.push({qid:r.qid,game,chinese:c.chinese,
        kind:'rsc_address',sourceId:c.sourceId,sourceLine:c.index,recordedAddress:c.recordedAddress,
        address:c.address,sourceSymbol:c.sourceSymbol,sourceFile:c.sourceFile,
        offsetWithinSymbol:c.offsetWithinSymbol,evidence:link.evidence,semanticStatus:'unreviewed'});
    }
    // Whole typed terms only: never apply dictionary replacement inside dialogue or nicknames.
    const dictionary=dictionaryByGroup.get(group);
    if (dictionary) {
      for (const d of dictionary.entries.filter(d => termKey(d.english)===termKey(r.english))) {
        candidates.push({qid:r.qid,game,chinese:d.chinese,kind:dictionary.type,sourceId:dictionary.source.id,
          sourceLine:d.line,recordedAddress:'',address:'',sourceSymbol:legacyName,sourceFile:dictionary.source.path,
          offsetWithinSymbol:'',evidence:d.english.toUpperCase()===r.english.toUpperCase()?'typed_dictionary_case_insensitive':'typed_dictionary_compacted_name',semanticStatus:'unreviewed'});
      }
    }
    if (candidates.length===candidateStart) gaps.push({qid:r.qid,game,
      reason:error?'unsupported_english_encoding':addresses.length?'rsc_translation_missing':'english_source_unmatched',detail:error});
  }
  engineSummary[game]={rscEntries:entries.length,reconstructedBytes:engine.memory.size,reconstructionErrors:engine.errors.length,encodingErrors};
}
for (const [i,c] of candidates.entries()) c.id=`candidate-${String(i+1).padStart(6,'0')}`;
const reviews=JSON.parse(read(path.join(root,'corpus/reviews.json')));
const recordMap=new Map(records.map(r=>[r.qid,r]));
const approved=[], usedReviews=new Set();
for (const review of reviews) {
  const r=recordMap.get(review.qid);
  if (!r || !['ruby','sapphire'].includes(review.game) || (r.game!=='both' && r.game!==review.game)) throw Error('Invalid review target');
  const key=`${r.qid}:${review.game}`;
  if (usedReviews.has(key)) throw Error(`Duplicate review ${key}`);
  usedReviews.add(key);
  applyReview(review,r,candidates);
  for (const c of candidates.filter(c=>c.qid===r.qid&&c.game===review.game)) {
    c.semanticStatus=c.chinese===review.chinese?`${review.method}_retained`:`${review.method}_superseded`;
  }
  const variables=tokensIn(r.japanese);
  // This first runtime pack admits only complete static source records; templates and paging are audited separately.
  if (variables.length || /\\[nrc]/.test(r.japanese) || /\\|\{|\[/.test(review.chinese) || !r.japanese) throw Error(`Non-static review requires semantic/variable rules: ${key}`);
  approved.push({id:key,qid:r.qid,game:review.game,japanese:r.japanese,chinese:review.chinese,
    kind:review.kind,reviewMethod:review.method,reviewAction:review.action,reason:review.reason,
    originalChinese:review.originalChinese,sourceCandidates:candidates.filter(c=>c.qid===r.qid&&c.game===review.game).map(c=>c.id)});
}
const groups=new Map();
for (const c of candidates) {
  const r=recordMap.get(c.qid),key=`${c.game}\0${r.japanese}`,g=groups.get(key)||{game:c.game,japanese:r.japanese,candidates:[],translations:new Set(),qids:new Set()};
  g.candidates.push(c.id);g.translations.add(c.chinese);g.qids.add(c.qid);groups.set(key,g);
}
const conflicts=[...groups.values()].filter(g=>g.translations.size>1).map(g=>{
  const related=records.filter(r=>r.japanese===g.japanese&&(r.game==='both'||r.game===g.game));
  const decisions=approved.filter(a=>a.game===g.game&&a.japanese===g.japanese);
  const complete=related.every(r=>usedReviews.has(`${r.qid}:${g.game}`));
  return {game:g.game,japanese:g.japanese,qids:[...g.qids],translations:[...g.translations],candidateIds:g.candidates,
    status:!complete?'unresolved':new Set(decisions.map(a=>a.chinese)).size===1?'resolved_offline':'context_required'};
});
const runtimeGroups=new Map();
for (const a of approved) {
  const key=`${a.game}\0${a.japanese}`,g=runtimeGroups.get(key)||[];g.push(a);runtimeGroups.set(key,g);
}
// All source candidates for a homograph must be explicitly reviewed before publication.
const publishable=[],held=[];
for (const [key,list] of runtimeGroups) {
    const missing=records.filter(r=>r.japanese===list[0].japanese && (r.game==='both'||r.game===list[0].game))
      .map(r=>r.qid).filter(qid=>!usedReviews.has(`${qid}:${list[0].game}`));
  if (new Set(list.map(a=>a.chinese)).size>1 || missing.length) held.push({game:list[0].game,japanese:list[0].japanese,missingReviews:missing,
    reason:missing.length?'unreviewed_homograph':'context_required',translations:[...new Set(list.map(a=>a.chinese))]});
  else publishable.push(...list);
}
const variableCounts={};
for (const r of records) for (const token of tokensIn(r.japanese)) variableCounts[token]=(variableCounts[token]||0)+1;
const variableRules=JSON.parse(read(path.join(root,'corpus/variable-rules.json')));
const variableAudit=Object.entries(variableCounts).sort(([a],[b])=>a.localeCompare(b,'en')).map(([token,occurrences])=>{
  const rule=variableRules.rules.find(r=>new RegExp(r.pattern).test(token))||variableRules.fallback;
  return {token,occurrences,kind:rule.kind,status:rule.status,binding:rule.binding,reference:rule.reference||''};
});
const unitRows=records.filter(r=>/\\[nrc]|\[/.test(r.japanese)).map(r=>({qid:r.qid,
  newlines:(r.japanese.match(/\\n/g)||[]).length,scrolls:(r.japanese.match(/\\r/g)||[]).length,
  clears:(r.japanese.match(/\\c/g)||[]).length,tokens:tokensIn(r.japanese).join('|'),status:'requires_printing_and_semantic_review'}));
writeCsv('records.csv',records,['qid','line','game','japanese','english']);
writeCsv('candidates.csv',candidates,['id','qid','game','chinese','kind','sourceId','sourceLine','recordedAddress','address','sourceSymbol','sourceFile','offsetWithinSymbol','evidence','semanticStatus']);
writeCsv('source-links.csv',sourceLinks,['qid','game','address','symbolAddress','sourceSymbol','offsetWithinSymbol','sourceFile','evidence','legacySymbol']);
writeCsv('rsc-import.csv',rscRows,['game','index','sourceId','recordedAddress','address','declaredBytes','actualBytes','sourceSymbol','symbolAddress','offsetWithinSymbol','offsetWithinField','sourceFile','chinese','correction','englishBytesSha256']);
writeCsv('gaps.csv',gaps,['qid','game','reason','detail']);
writeCsv('semantic-worklist.csv',unitRows,['qid','newlines','scrolls','clears','tokens','status']);
writeCsv('variables.csv',variableAudit,['token','occurrences','kind','status','binding','reference']);
writeJson('conflicts.json',conflicts);
writeJson('runtime.json',{schemaVersion:1,scope:'reviewed_complete_static_records_only',records:publishable});
const countBy=(items,key)=>Object.fromEntries([...new Set(items.map(x=>x[key]))].sort().map(k=>[k,items.filter(x=>x[key]===k).length]));
const summary={schemaVersion:1,sourceManifestSha256:sha256(fs.readFileSync(path.join(root,'corpus/sources.json'))),
  corpusRecords:records.length,japanese:{empty:records.filter(r=>!r.japanese).length,null:records.filter(r=>r.japanese==='[NULL]').length},
  english:{empty:records.filter(r=>!r.english).length,null:records.filter(r=>r.english==='[NULL]').length},
  recordApplicability:countBy(records,'game'),engines:engineSummary,candidateRows:candidates.length,candidateKinds:countBy(candidates,'kind'),
  perGame:Object.fromEntries(['ruby','sapphire'].map(game=>[game,{eligibleSourceRecords:records.filter(r=>r.game==='both'||r.game===game).length,
    recordsWithChineseCandidates:new Set(candidates.filter(c=>c.game===game).map(c=>c.qid)).size,
    recordsWithSourceLinks:new Set(sourceLinks.filter(c=>c.game===game).map(c=>c.qid)).size,
    homographGroups:countBy(conflicts.filter(c=>c.game===game),'status'),gaps:countBy(gaps.filter(g=>g.game===game),'reason'),
    reviewedRecords:approved.filter(a=>a.game===game).length,publishableStaticRecords:publishable.filter(a=>a.game===game).length}])),
  sourceLinks:sourceLinks.length,addressCorrections:corrections.map(c=>({...c,recorded:hex(c.recorded),corrected:hex(c.corrected)})),
  semanticWorklistRecords:unitRows.length,tokenOccurrences:variableCounts,heldReviews:held,
  semanticAcceptance:'not_complete',runtimeIntegration:'S7_pending',denominator:'all pinned RS records; includes out-of-first-release scope; not screenshot/runtime coverage'};
writeJson('summary.json',summary);
writeJson('build-manifest.json',{schemaVersion:1,inputs:manifest.sources,
  implementation:['tools/build_corpus.mjs','tools/corpus_source.mjs','tools/corpus_common.mjs','tools/prepare_corpus.mjs','corpus/reviews.json','corpus/variable-rules.json'].map(local=>({local,sha256:sha256(fs.readFileSync(path.join(root,local)))})),
  outputs:fs.readdirSync(out).filter(f=>f!=='build-manifest.json').sort().map(file=>({file,sha256:sha256(fs.readFileSync(path.join(out,file)))}))});
console.log(JSON.stringify({records:records.length,candidates:candidates.length,perGame:summary.perGame},null,2));
